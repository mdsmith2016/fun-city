/**
 * A new wardrobe for the same skater: every clothing item is drawn independently at random from the whole
 * roster's pieces and colours, so outfits are deliberately uncoordinated. Body, hair, glasses and board stay.
 * A top's colour and its pattern travel together (the check is a fabric, not a separate piece).
 */
export function randomWardrobe(base: Appearance): Appearance {
  const pick = <T>(of: (a: Appearance) => T): T => of(ROSTER[Math.floor(Math.random() * ROSTER.length)]);
  const hat = pick((a) => ({ cap: a.cap, capDir: a.capDir, beanie: a.beanie }));
  const fabric = pick((a) => ({ top: a.top, topPattern: a.topPattern }));
  return {
    ...base,
    cap: hat.cap,
    capDir: hat.capDir,
    beanie: hat.beanie,
    top: fabric.top,
    topPattern: fabric.topPattern,
    topStyle: pick((a) => a.topStyle),
    bottom: pick((a) => a.bottom),
    bottomStyle: pick((a) => a.bottomStyle),
    shoes: pick((a) => a.shoes),
  };
}

/** The name to show right now: skaters with an `altName` flip between the two spellings every second. */
export function skaterName(a: Appearance): string {
  return a.altName && Math.floor(Date.now() / 1000) % 2 === 1 ? a.altName : a.name;
}
